package kernelplan

import (
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"os"
)

// GoldenPrompt describes one prompt and its expected greedy token sequence.
type GoldenPrompt struct {
	IDs    []int32 `json:"ids"`
	Tokens []int32 `json:"tokens"`
}

// GoldenFile holds the checked-in reference tokens for a model.
type GoldenFile struct {
	Format          string         `json:"format"`
	TokensPerPrompt int            `json:"tokens_per_prompt"`
	Source          string         `json:"source"`
	Prompts         []GoldenPrompt `json:"prompts"`
	Digest          string         `json:"-"`
}

// ParseGoldenJSON parses golden tokens JSON data, recording its SHA-256 digest.
func ParseGoldenJSON(data []byte) (*GoldenFile, error) {
	var gf GoldenFile
	if err := json.Unmarshal(data, &gf); err != nil {
		return nil, fmt.Errorf("unmarshal golden json: %w", err)
	}
	if gf.Format != "vxpu-golden/1" {
		return nil, fmt.Errorf("unknown golden format %q, expected vxpu-golden/1", gf.Format)
	}
	gf.Digest = fmt.Sprintf("%x", sha256.Sum256(data))
	return &gf, nil
}

// ReadGoldenFile reads and parses a golden tokens JSON file, recording its SHA-256 digest.
func ReadGoldenFile(path string) (*GoldenFile, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read golden file %s: %w", path, err)
	}
	gf, err := ParseGoldenJSON(data)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return gf, nil
}

// GoldenMismatchError records a failure of the golden token verification check.
type GoldenMismatchError struct {
	// Prompt is the zero-based index of the golden prompt that differed.
	Prompt int
	// Position is the zero-based token position within the prompt that first differed.
	Position int
	// Got is the token ID generated by the executor.
	Got int32
	// Expected is the expected token ID recorded in the golden reference document.
	Expected int32
	// Msg is the formatted explanation of the mismatch.
	Msg string
}

func (e *GoldenMismatchError) Error() string {
	return e.Msg
}

// CompareTokens compares produced token sequences against the expected sequences in golden.
// If any prompt differs, it returns a *GoldenMismatchError naming the prompt and first differing position.
func CompareTokens(golden *GoldenFile, producedTokens [][]int32) error {
	if len(producedTokens) != len(golden.Prompts) {
		return &GoldenMismatchError{
			Msg: fmt.Sprintf("golden values: expected %d prompts, got %d", len(golden.Prompts), len(producedTokens)),
		}
	}
	for i, prompt := range golden.Prompts {
		got := producedTokens[i]
		want := prompt.Tokens
		minLen := len(got)
		if len(want) < minLen {
			minLen = len(want)
		}
		for pos := 0; pos < minLen; pos++ {
			if got[pos] != want[pos] {
				return &GoldenMismatchError{
					Prompt:   i,
					Position: pos,
					Got:      got[pos],
					Expected: want[pos],
					Msg:      fmt.Sprintf("golden values: prompt %d differs first at position %d: got %d, expected %d", i, pos, got[pos], want[pos]),
				}
			}
		}
		if len(got) != len(want) {
			return &GoldenMismatchError{
				Prompt:   i,
				Position: minLen,
				Msg:      fmt.Sprintf("golden values: prompt %d differs first at position %d: got %d tokens, expected %d", i, minLen, len(got), len(want)),
			}
		}
	}
	return nil
}
