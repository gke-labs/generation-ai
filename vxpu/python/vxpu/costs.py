"""CUDA graph capture and timing utilities."""

import torch


def _flat(fn, warmup=3):
    """Capture fn into a CUDA graph after warmup."""
    for _ in range(warmup):
        fn()
    torch.cuda.synchronize()
    g = torch.cuda.CUDAGraph()
    with torch.cuda.graph(g):
        fn()
    torch.cuda.synchronize()
    return g


def _replay_us(g, iters=100, warmup=5):
    """Execution time of replaying CUDA graph g, in microseconds."""
    for _ in range(warmup):
        g.replay()
    torch.cuda.synchronize()
    start = torch.cuda.Event(enable_timing=True)
    end = torch.cuda.Event(enable_timing=True)
    start.record()
    for _ in range(iters):
        g.replay()
    end.record()
    torch.cuda.synchronize()
    return (start.elapsed_time(end) * 1000.0) / iters
